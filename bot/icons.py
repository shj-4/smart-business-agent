"""
نظام أيقونات موحّد — فئة واحدة = أيقونة واحدة.

كل نص يظهر في واجهة البوت يمرّ بالثوابت هنا بدل الأحرف المبعثرة في ملفات
عدة. هذا يضمن أن المستخدم يتعلّم أن 🔻 تعني "مصروف" و🔺 تعني "إيراد"而不
تتغيّر المعاني من شاشة لأخرى.

التصنيف:
  - مال يخرج (مصروف/دفع/سداد) → EXPENSE
  - مال يدخل (إيراد/استلام)     → INCOME
  - مهام / تذكير                → TASK
  - تحذير / تجاوز               → WARNING
  - إجراء ناجح (تأكيد)          → SUCCESS
  - خطأ                          → ERROR
  - تنقّل خلفي (رجوع)           → BACK
  - تنقّل أمامي (_pagination)    → FORWARD
  - رئيسية (القائمة الرئيسية)    → HOME
"""

# ── مال ──────────────────────────────────────────────────────────
EXPENSE = "🔻"  # مصروف / دفع / سداد
INCOME = "🔺"  # إيراد / استلام
NEW = "➕"  # إجراء إنشاء/تسجيل جديد (محايد لا يصنّف العملية نفسها)

# ── مهام / تذكير ────────────────────────────────────────────────
TASK = "🗓️"  # كل ما يخص Task / المهام المعلّقة

# ── ملاحظات بصرية ───────────────────────────────────────────────
WARNING = "⚠️"  # تحذير / تجاوز / سقف فقط — لا يُستخدم في التنقّل
SUCCESS = "✔️"  # إجراء ناجح / تم الحفظ / تأكيد فقط
ERROR = "❌"  # خطأ / فشل

# ── تنقّل (محايد الاتجاه — لا يتضارب مع RTL) ───────────────────
BACK = "‹"  # رجوع (U+2039 — زاوية محايدة بدل ⬅️ LTR)
FORWARD = "›"  # تقدم / صفحة تالية (U+203A — زاوية محايدة بدل ➡️ LTR)
