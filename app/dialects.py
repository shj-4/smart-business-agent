# ضمائر الملكية الملحقة بالكلمة العامية (شلونك/وينك/كيفك...). نجردها للوصول
# إلى الجذر لكن دون كسر الكلمات القصيرة جدًا (≥3 أحرف بعد التجريد).
_SUFFIXES = ("كم", "ها", "نا", "هم", "كن", "ك", "ه", "ي")

_WEIGHT = {
    EGYPTIAN: 1,
    LEVANTINE: 2,
    GULF: 2,
    MAGHREBI: 1,
}


def _norms(text: str) -> set[str]:
    """يطهّر النص: يزيل الهمزات والوسوم، ويضيف جذور الكلمات بعد تجريد اللواحق."""
    import re

    t = text.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا").replace("ى", "ي")
    t = re.sub(r"[?؟!.,،\"'\-:؛_\n\t]", " ", t)
    words = {w for w in t.split() if w}
    out = set(words)
    for w in words:
        for suf in _SUFFIXES:
            if w.endswith(suf) and len(w) - len(suf) >= 3:
                out.add(w[: -len(suf)])
    return out


def detect_dialect(text: str) -> str:
    """يكشف اللهجة التقريبية للنص عبر تطابق الكلمات المميزة.

    يعيد MSA إذا لم تتجاوز أي مجموعة عتبة (نسبة/عدد كاف).
    """
    if not text or not text.strip():
        return MSA
    words = _norms(text)
    total = len(words)
    if total == 0:
        return MSA

    scores = {r: 0 for r in (LEVANTINE, GULF, EGYPTIAN, MAGHREBI)}
    for w in words:
        if w in _EGYPTIAN:
            scores[EGYPTIAN] += 1
        if w in _LEVANTINE:
            scores[LEVANTINE] += 1
        if w in _GULF:
            scores[GULF] += 1
        if w in _MAGHREBI:
            scores[MAGHREBI] += 1

    best_label, best_score = max(scores.items(), key=lambda kv: (kv[1], _WEIGHT[kv[0]]))

    # لا نُعلن لهجة إلا بتطابق موثوق:
    # - رسالة طويلة (6+): كلمة شائعة واحدة لا تكفي وسط الكثير → نطلب 2.
    # - رسالة متوسطة (3-5): كلمة مميزة واحدة تكفي عندما تكون الرسالة فعلًا لهجوية.
    # - رسالة قصيرة جدًا (<3): الكلمة الوحيدة قد تكون عامة/صدفة → نطلب 2 أيضًا
    #   آخر إعلانًا لهجة كاملة من كلمة واحدة على نص قصير غير موثوق.
    threshold = 2 if (total < 3 or total >= 6) else 1
    if best_score >= threshold and best_score > 0:
        return best_label
    return MSA


_NAMES = {
    LEVANTINE: "لهجة شامية (فلسطين/لبنان/سوريا/الأردن)",
    EGYPTIAN: "لهجة مصرية",
    GULF: "لهجة خليجية",
    MAGHREBI: "لهجة مغاربية (المغرب/الجزائر/تونس/ليبيا)",
    MSA: "عربية فصحى",
}


def dialect_label(dialect: str) -> str:
    """اسم عرض عربي للهجة."""
    return _NAMES.get(dialect, _NAMES[MSA])


